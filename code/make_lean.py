#!/usr/bin/env python3
"""Generate the Lean certificates in lean/BalancedLatin/Certificates/ from the data files.

For every rectangle in results/rectangles/ (the 51 benchmark instances) and in
results/k2_large/ (2 x n, n >= 14) this writes a Lean definition of the rows, copied
verbatim from the file, and three theorems that the Lean kernel checks by evaluation
(`decide +kernel`): the rectangle is Latin, the columns are read faithfully from the rows,
and 3*I equals the claimed value. The claimed values are taken from results/results.csv
(benchmark) and from the file headers (k = 2), and are cross-checked against code/verify.py.

Usage: make_lean.py            # regenerate; fails if any claimed value disagrees
"""
import csv
import glob
import os
import re
import sys
from fractions import Fraction

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from verify import read_rectangle, imbalance  # noqa: E402

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, 'lean', 'BalancedLatin', 'Certificates')

HEADER = """\
-- AUTOMATICALLY GENERATED by code/make_lean.py from {src}. Do not edit.
import BalancedLatin.Defs

/-!
# Certificates: {title}

Each rectangle below is copied verbatim from its data file. For each one the Lean kernel
checks, by evaluation, that it is a Latin rectangle, that `colOfRows` reads it faithfully,
and that `3·I` has the stated value. Only `BalancedLatin.Defs` (core Lean) is trusted.
-/

namespace BalancedLatin.Certificates
open BalancedLatin LatinRect
"""


def fmt(imb3):
    q, r = divmod(imb3, 3)
    return f"{q}" + ["", "⅓", "⅔"][r]


def block(name, path, R, imb3):
    k, n = len(R), len(R[0])
    rows = ",\n    ".join("[" + ", ".join(map(str, r)) + "]" for r in R)
    rel = os.path.relpath(path, ROOT)
    return f"""
/-- `{rel}`: a {k} × {n} Latin rectangle with imbalance {fmt(imb3)} (`3·I = {imb3}`). -/
def rows_{name} : List (List Nat) :=
  [{rows}]

/-- The {k} × {n} rectangle of `{rel}`; both Latin conditions are checked by the kernel. -/
def rect_{name} : LatinRect {k} {n} where
  col := colOfRows rows_{name}
  row_inj := by decide +kernel
  col_inj := by decide +kernel

theorem faithful_{name} : Faithful {k} {n} rows_{name} := by decide +kernel

theorem imb3_{name} : rect_{name}.imb3 = {imb3} := by decide +kernel

/-- There is a {k} × {n} Latin rectangle with `3·I = {imb3}`, i.e. `I = {fmt(imb3)}`. -/
theorem exists_{name} : ∃ L : LatinRect {k} {n}, L.imb3 = {imb3} := ⟨rect_{name}, imb3_{name}⟩
"""


def check(R, claimed, path):
    got = 3 * imbalance(R)
    if got != claimed or Fraction(got).denominator != 1:
        raise SystemExit(f"{path}: claimed 3I = {claimed}, checker gives {got}")
    return int(got)


def main():
    os.makedirs(OUT, exist_ok=True)
    claimed = {}
    with open(os.path.join(ROOT, 'results', 'results.csv')) as fh:
        for row in csv.DictReader(fh):
            claimed[(int(row['k']), int(row['n']))] = int(row['new_imbalance3'])
    modules = []

    # Benchmark instances, one file per n.
    for n in range(8, 14):
        parts = [HEADER.format(src='results/rectangles/', title=f'benchmark instances with n = {n}')]
        for k in range(2, n):
            path = os.path.join(ROOT, 'results', 'rectangles', f'k{k}_n{n}.txt')
            R = read_rectangle(path)
            assert (len(R), len(R[0])) == (k, n), path
            parts.append(block(f'k{k}_n{n}', path, R, check(R, claimed[(k, n)], path)))
        parts.append("\nend BalancedLatin.Certificates\n")
        name = f'N{n}'
        open(os.path.join(OUT, name + '.lean'), 'w').write("".join(parts))
        modules.append(name)

    # Two-row rectangles beyond the proven range.
    parts = [HEADER.format(src='results/k2_large/', title='2 × n rectangles, 14 ≤ n ≤ 64')]
    files = sorted(glob.glob(os.path.join(ROOT, 'results', 'k2_large', 'k2_n*.txt')),
                   key=lambda p: int(re.search(r'n(\d+)', p).group(1)))
    for path in files:
        R = read_rectangle(path)
        m = re.search(r'3I=(\d+)', open(path).readline())
        parts.append(block(os.path.basename(path)[:-4], path, R, check(R, int(m.group(1)), path)))
    parts.append("\nend BalancedLatin.Certificates\n")
    open(os.path.join(OUT, 'TwoRow.lean'), 'w').write("".join(parts))
    modules.append('TwoRow')

    with open(os.path.join(ROOT, 'lean', 'BalancedLatin', 'Certificates.lean'), 'w') as fh:
        fh.write("-- AUTOMATICALLY GENERATED by code/make_lean.py. Do not edit.\n")
        fh.write("".join(f"import BalancedLatin.Certificates.{m}\n" for m in modules))
    print(f"wrote {len(modules)} certificate modules to {os.path.relpath(OUT, ROOT)}")


if __name__ == '__main__':
    main()
